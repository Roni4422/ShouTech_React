-- A posted journal must have at least one line and equal debit/credit totals.
CREATE OR REPLACE FUNCTION shouttech_validate_balanced_journal() RETURNS trigger AS $$
DECLARE
    line_count bigint;
    total_debit numeric(19,4);
    total_credit numeric(19,4);
BEGIN
    IF NEW.status = 1 AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM NEW.status) THEN
        SELECT count(*), COALESCE(sum(debit),0), COALESCE(sum(credit),0)
          INTO line_count, total_debit, total_credit
          FROM journal_entry_lines WHERE journal_entry_id = NEW.journal_entry_id;
        IF line_count < 2 THEN RAISE EXCEPTION 'A journal entry requires at least two lines'; END IF;
        IF total_debit <= 0 OR total_debit <> total_credit THEN
            RAISE EXCEPTION 'Journal entry is not balanced: debit % credit %', total_debit, total_credit;
        END IF;
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_journal_must_balance ON journal_entries;
CREATE TRIGGER trg_journal_must_balance BEFORE UPDATE OF status ON journal_entries
FOR EACH ROW EXECUTE FUNCTION shouttech_validate_balanced_journal();

-- Ledger facts are immutable. Post compensating entries rather than rewriting history.
CREATE OR REPLACE FUNCTION shouttech_reject_stock_ledger_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Stock ledger entries are immutable; create a reversing entry';
END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_stock_ledger_no_update ON stock_ledger_entries;
CREATE TRIGGER trg_stock_ledger_no_update BEFORE UPDATE OR DELETE ON stock_ledger_entries
FOR EACH ROW EXECUTE FUNCTION shouttech_reject_stock_ledger_mutation();
