-- ShouTech ERP commercial operations schema (PostgreSQL).
-- Additive migration: preserves existing records and legacy table contracts.
-- Financial and inventory ledgers are append-only; corrections use reversing records.

CREATE TABLE IF NOT EXISTS product_categories (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    category_code varchar(50) NOT NULL,
    name_ar varchar(200) NOT NULL,
    name_en varchar(200),
    parent_category_id bigint REFERENCES product_categories(category_id),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(company_id, category_code)
);
CREATE INDEX IF NOT EXISTS ix_product_categories_parent ON product_categories(company_id, parent_category_id);

CREATE TABLE IF NOT EXISTS warehouses (
    warehouse_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    warehouse_code varchar(50) NOT NULL,
    name_ar varchar(200) NOT NULL,
    name_en varchar(200),
    address varchar(500),
    is_default boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    is_deleted boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(company_id, warehouse_code)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_warehouses_default_per_company ON warehouses(company_id) WHERE is_default AND NOT is_deleted;

CREATE TABLE IF NOT EXISTS business_parties (
    party_id uuid PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    party_code varchar(50) NOT NULL,
    party_type varchar(20) NOT NULL CHECK (party_type IN ('CUSTOMER','SUPPLIER','BOTH','EMPLOYEE','OTHER')),
    name_ar varchar(250) NOT NULL,
    name_en varchar(250),
    tax_number varchar(100),
    email varchar(250),
    phone varchar(80),
    mobile varchar(80),
    address text,
    credit_limit numeric(19,4) NOT NULL DEFAULT 0 CHECK (credit_limit >= 0),
    payment_terms_days integer NOT NULL DEFAULT 0 CHECK (payment_terms_days >= 0),
    is_active boolean NOT NULL DEFAULT true,
    is_deleted boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz,
    UNIQUE(company_id, party_code)
);
CREATE INDEX IF NOT EXISTS ix_business_parties_name_ar ON business_parties(company_id, name_ar);
CREATE INDEX IF NOT EXISTS ix_business_parties_tax ON business_parties(company_id, tax_number) WHERE tax_number IS NOT NULL;

CREATE TABLE IF NOT EXISTS currencies (
    currency_code char(3) PRIMARY KEY,
    name_ar varchar(100) NOT NULL,
    name_en varchar(100) NOT NULL,
    minor_units smallint NOT NULL DEFAULT 2 CHECK (minor_units BETWEEN 0 AND 6),
    is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS company_currencies (
    company_id uuid NOT NULL REFERENCES companies(company_id),
    currency_code char(3) NOT NULL REFERENCES currencies(currency_code),
    is_base boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    PRIMARY KEY(company_id, currency_code)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_company_base_currency ON company_currencies(company_id) WHERE is_base;

CREATE TABLE IF NOT EXISTS tax_codes (
    tax_code_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    code varchar(40) NOT NULL,
    name_ar varchar(150) NOT NULL,
    name_en varchar(150),
    rate numeric(9,6) NOT NULL CHECK (rate >= 0 AND rate <= 100),
    recoverable boolean NOT NULL DEFAULT true,
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE(company_id, code)
);

CREATE TABLE IF NOT EXISTS cost_centers (
    cost_center_id uuid PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    cost_center_code varchar(50) NOT NULL,
    name_ar varchar(200) NOT NULL,
    name_en varchar(200),
    parent_cost_center_id uuid REFERENCES cost_centers(cost_center_id),
    is_active boolean NOT NULL DEFAULT true,
    is_deleted boolean NOT NULL DEFAULT false,
    UNIQUE(company_id, cost_center_code)
);
CREATE INDEX IF NOT EXISTS ix_cost_centers_parent ON cost_centers(company_id, parent_cost_center_id);

CREATE TABLE IF NOT EXISTS commercial_documents (
    document_id uuid PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    document_type varchar(30) NOT NULL CHECK (document_type IN ('SALES_INVOICE','PURCHASE_INVOICE','SALES_RETURN','PURCHASE_RETURN','QUOTATION','CREDIT_NOTE','DEBIT_NOTE')),
    document_number varchar(60) NOT NULL,
    party_id uuid REFERENCES business_parties(party_id),
    document_date date NOT NULL,
    due_date date,
    currency_code char(3) NOT NULL REFERENCES currencies(currency_code),
    exchange_rate numeric(19,8) NOT NULL DEFAULT 1 CHECK (exchange_rate > 0),
    status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','APPROVED','POSTED','CANCELLED','REVERSED')),
    subtotal numeric(19,4) NOT NULL DEFAULT 0,
    discount_total numeric(19,4) NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
    tax_total numeric(19,4) NOT NULL DEFAULT 0,
    grand_total numeric(19,4) NOT NULL DEFAULT 0,
    paid_total numeric(19,4) NOT NULL DEFAULT 0 CHECK (paid_total >= 0),
    notes text,
    source_document_id uuid REFERENCES commercial_documents(document_id),
    journal_entry_id uuid REFERENCES journal_entries(journal_entry_id),
    created_by varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_by varchar(100),
    updated_at timestamptz,
    posted_by varchar(100),
    posted_at timestamptz,
    reversed_by varchar(100),
    reversed_at timestamptz,
    reversal_reason varchar(1000),
    UNIQUE(company_id, document_type, document_number),
    CHECK (due_date IS NULL OR due_date >= document_date),
    CHECK (grand_total >= 0)
);
CREATE INDEX IF NOT EXISTS ix_commercial_documents_date ON commercial_documents(company_id, document_type, document_date, status);
CREATE INDEX IF NOT EXISTS ix_commercial_documents_party_due ON commercial_documents(company_id, party_id, due_date, status);
CREATE INDEX IF NOT EXISTS ix_commercial_documents_journal ON commercial_documents(company_id, journal_entry_id) WHERE journal_entry_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS commercial_document_lines (
    line_id uuid PRIMARY KEY,
    document_id uuid NOT NULL REFERENCES commercial_documents(document_id),
    line_number integer NOT NULL CHECK (line_number > 0),
    product_id integer REFERENCES products(product_id),
    description varchar(500) NOT NULL,
    quantity numeric(18,6) NOT NULL CHECK (quantity > 0),
    unit_price numeric(19,6) NOT NULL CHECK (unit_price >= 0),
    discount_rate numeric(9,6) NOT NULL DEFAULT 0 CHECK (discount_rate BETWEEN 0 AND 100),
    discount_amount numeric(19,4) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_code_id bigint REFERENCES tax_codes(tax_code_id),
    tax_rate numeric(9,6) NOT NULL DEFAULT 0 CHECK (tax_rate BETWEEN 0 AND 100),
    tax_amount numeric(19,4) NOT NULL DEFAULT 0,
    line_total numeric(19,4) NOT NULL DEFAULT 0,
    warehouse_id bigint REFERENCES warehouses(warehouse_id),
    UNIQUE(document_id, line_number)
);
CREATE INDEX IF NOT EXISTS ix_commercial_document_lines_product ON commercial_document_lines(product_id, document_id);

CREATE TABLE IF NOT EXISTS payments (
    payment_id uuid PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    payment_number varchar(60) NOT NULL,
    payment_type varchar(20) NOT NULL CHECK (payment_type IN ('RECEIPT','DISBURSEMENT','REFUND')),
    party_id uuid REFERENCES business_parties(party_id),
    payment_date date NOT NULL,
    currency_code char(3) NOT NULL REFERENCES currencies(currency_code),
    exchange_rate numeric(19,8) NOT NULL DEFAULT 1 CHECK (exchange_rate > 0),
    amount numeric(19,4) NOT NULL CHECK (amount > 0),
    payment_method varchar(30) NOT NULL CHECK (payment_method IN ('CASH','BANK','CARD','CHEQUE','TRANSFER','OTHER')),
    reference_number varchar(150),
    status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','POSTED','CANCELLED','REVERSED')),
    journal_entry_id uuid REFERENCES journal_entries(journal_entry_id),
    notes text,
    created_by varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    posted_by varchar(100),
    posted_at timestamptz,
    UNIQUE(company_id, payment_number)
);
CREATE INDEX IF NOT EXISTS ix_payments_party_date ON payments(company_id, party_id, payment_date, status);

