    customer_id BIGINT,
    manager_id BIGINT,
    start_date DATE,
    end_date DATE,
    budget_amount NUMERIC(20,6) NOT NULL DEFAULT 0,
    external_code VARCHAR(120),
    email VARCHAR(254),
    phone VARCHAR(50),
